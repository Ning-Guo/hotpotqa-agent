#!/usr/bin/env python3
"""
exp6_grpo_naive_rag.py — Experiment 6: GRPO model + Naive single-hop RAG

Same retrieval as Exp0 (original question, no decomposition), but the final
answer is generated by the GRPO-tuned adapter instead of the base model.

This isolates the contribution of GRPO training from the agent pipeline:
  - Exp0: base model  + single-hop RAG  → EM=0.568
  - Exp6: GRPO model  + single-hop RAG  → ?
  - Exp3: GRPO model  + multi-hop agent → EM=0.540

If Exp6 > Exp0: GRPO adapter improves answer quality even without multi-hop.
If Exp6 ≈ Exp0: GRPO adapter was only useful in the multi-hop context it was trained on.

Usage:
    python eval/exp6_grpo_naive_rag.py --load-index
    python eval/exp6_grpo_naive_rag.py --n 100 --load-index
"""

from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import torch
from tqdm import tqdm
from utils import load_jsonl, build_corpus, get_gold_titles, print_summary

import config
from src.models import load_model_and_tokenizer
from src.retriever import Retriever
from src.evaluator import exact_match, token_f1, supporting_fact_recall, \
                          answer_coverage, faithfulness, summarize

RESULTS_DIR = os.path.join(ROOT, "results")


def generate_answer(model, tokenizer, device: str,
                    question: str, retrieved_meta: list,
                    max_new_tokens: int = 64) -> str:
    """Generate answer with GRPO adapter active (same prompt as Exp0, adapter ON)."""
    ctx = "\n\n".join(
        f"[{i+1}] {p['title']}\n{p['text']}" for i, p in enumerate(retrieved_meta)
    )
    content = (
        "Answer the question using the passages. "
        "Give a short answer phrase only — no explanation.\n\n"
        f"{ctx}\n\n"
        f"Question: {question}"
    )
    messages = [{"role": "user", "content": content}]
    prompt = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    inputs = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=3072)
    inputs = {k: v.to(device) for k, v in inputs.items()}
    input_len = inputs["input_ids"].shape[1]

    with torch.no_grad():
        # GRPO adapter active — no disable_adapter() unlike Exp0
        outputs = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,
            pad_token_id=tokenizer.eos_token_id,
        )
    return tokenizer.decode(outputs[0][input_len:], skip_special_tokens=True).strip()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model",      default=config.MODEL_NAME)
    parser.add_argument("--adapter",    default=config.GRPO_ADAPTER_REPO)
    parser.add_argument("--eval",       default=config.EVAL_PATH)
    parser.add_argument("--top-k",      type=int, default=config.TOP_K)
    parser.add_argument("--n",          type=int, default=None)
    parser.add_argument("--load-index", action="store_true")
    parser.add_argument("--output",     default=None)
    args = parser.parse_args()

    os.makedirs(RESULTS_DIR, exist_ok=True)
    if args.output is None:
        n_tag = f"_n{args.n}" if args.n else "_n500"
        args.output = os.path.join(RESULTS_DIR, f"exp6_grpo_naive_rag{n_tag}.json")

    # ── Load data ──────────────────────────────────────────────────────────
    items = load_jsonl(args.eval)
    if args.n:
        items = items[:args.n]
    print(f"Loaded {len(items)} questions from {args.eval}")

    # ── Load model (GRPO adapter) ──────────────────────────────────────────
    model, tokenizer, device = load_model_and_tokenizer(args.model, args.adapter)

    # ── Load retriever ─────────────────────────────────────────────────────
    if args.load_index:
        retriever = Retriever.load(
            config.INDEX_PATH, config.CORPUS_PATH, config.EMBEDDING_MODEL
        )
    else:
        corpus = build_corpus(items)
        retriever = Retriever(corpus, config.EMBEDDING_MODEL)
        retriever.save(config.INDEX_PATH, config.CORPUS_PATH)

    # ── Eval loop ──────────────────────────────────────────────────────────
    results = []
    for item in tqdm(items, desc="Evaluating"):
        question    = item["question"]
        gold_titles = get_gold_titles(item)

        retrieved_meta = retriever.retrieve_with_meta(question, top_k=args.top_k)

        try:
            pred = generate_answer(model, tokenizer, str(device), question, retrieved_meta)
        except Exception as e:
            print(f"\n[ERROR] {item['id']}: {e}")
            pred = ""

        results.append({
            "id":            item["id"],
            "question":      question,
            "gold":          item["answer"],
            "prediction":    pred,
            "type":          item.get("type"),
            "level":         item.get("level"),
            "em":            exact_match(pred, item["answer"]),
            "f1":            token_f1(pred, item["answer"]),
            "ctx_recall":    supporting_fact_recall(retrieved_meta, gold_titles),
            "ctx_precision": None,
            "ans_coverage":  answer_coverage(retrieved_meta, item["answer"]),
            "faithfulness":  faithfulness(pred, retrieved_meta),
            "entailment":    None,
            "contradiction": None,
            "outcome":       None,
        })

    # ── Summary ────────────────────────────────────────────────────────────
    summary = summarize(results)
    print_summary(summary, f"EXP 6 — GRPO ADAPTER + NAIVE RAG  (top_k={args.top_k})")

    print(f"\n  Comparison:")
    print(f"  Exp0 (base  + naive RAG)  : EM=0.5680  F1=0.6565")
    print(f"  Exp6 (GRPO  + naive RAG)  : EM={summary['em']:.4f}  F1={summary['f1']:.4f}  ← this run")
    print(f"  Exp3 (GRPO  + agent)      : EM=0.5400  F1=0.6250")
    print(f"  Exp4 (GRPO  + Query LoRA) : EM=0.5500  F1=0.6392")

    with open(args.output, "w") as f:
        json.dump({"config": vars(args), "summary": summary, "per_item": results}, f, indent=2)
    print(f"\nResults saved → {args.output}")


if __name__ == "__main__":
    main()
